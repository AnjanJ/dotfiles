#!/usr/bin/env bash
# doc: Migrate — `dotfiles migrate` against a fake repo: pending list and exit codes, filename order, each migration once with DOTFILES_DIR exported, a failing one kept pending while the rest run, `--dry-run` running and marking nothing, `--new` and its slug check, bash 3.2; and the repo's own migrations: every one parses, and the private-state-dir and drop-lsd-colors repairs do what they say and are idempotent
# ============================================
# MIGRATE TEST SUITE
# ============================================
# bin/dotfiles-migrate runs every sync and update. These tests drive it
# against a fake migrations directory and a sandbox state dir, then run
# the real migrations that only touch $HOME against the sandbox HOME.
# Usage: tests/run migrate   (or /opt/homebrew/bin/bash tests/migrate-test.sh)
# ============================================
set -euo pipefail
source "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/base-test.sh"

M="$ROOT/bin/dotfiles-migrate"
MOCK="$TEST_TMP/repo"
export DOTFILES_DIR="$MOCK" DOTFILES_STATE_DIR="$TEST_TMP/state"
LOG="$TEST_TMP/ran.log"
mkdir -p "$MOCK/migrations"

mig() {   # mig <name> <body>
    printf '#!/usr/bin/env bash\nset -euo pipefail\n%s\n' "$2" > "$MOCK/migrations/$1.sh"
}

echo ""
echo "╔═══════════════════════════════════════════════════════════╗"
echo "║   Migrate Tests                                           ║"
echo "╚═══════════════════════════════════════════════════════════╝"
echo ""

section "Test 1: Pending, order, once"
set +e; "$M" --pending >/dev/null; rc=$?; set -e
assert_eq "$rc" "1" "--pending exits 1 with nothing to do"
mig 200-second "echo second \$DOTFILES_DIR >> '$LOG'"
mig 100-first "echo first >> '$LOG'"
assert_eq "$("$M" --pending | tr '\n' ' ')" "100-first.sh 200-second.sh " "--pending lists them in filename order"
out=$("$M" --dry-run)
assert_contains "$out" "Would run: 100-first.sh" "--dry-run names what would run"
assert_file_not_exists "$LOG" "and runs nothing"
assert_eq "$("$M" --pending | wc -l | tr -d ' ')" "2" "and marks nothing"
"$M" >/dev/null
assert_eq "$(tr '\n' '|' < "$LOG")" "first|second $MOCK|" "both run in order, with DOTFILES_DIR exported"
assert_file_exists "$DOTFILES_STATE_DIR/migrations/100-first.sh" "a done migration is marked"
assert_eq "$("$M")" "No pending migrations" "a second run runs nothing"
assert_eq "$(wc -l < "$LOG" | tr -d ' ')" "2" "so nothing ran twice"
echo ""

section "Test 2: A failing migration stays pending"
mig 300-broken "exit 3"
mig 400-after "echo after >> '$LOG'"
set +e; out=$("$M" 2>&1); rc=$?; set -e
assert_eq "$rc" "1" "a failure makes the run exit 1"
assert_contains "$out" "FAILED (will retry on next sync/update)" "and says it will retry"
assert_file_contains "$LOG" "^after$" "the migrations after it still run"
assert_eq "$("$M" --pending)" "300-broken.sh" "only the broken one stays pending"
mig 300-broken "echo fixed >> '$LOG'"
"$M" >/dev/null
assert_file_contains "$LOG" "^fixed$" "once fixed it runs on the next pass"
echo ""

section "Test 3: --new"
out=$("$M" --new tidy-things)
f=$(ls "$MOCK"/migrations/*-tidy-things.sh)
assert_contains "$out" "Created $f" "--new creates a timestamped file"
assert_file_contains "$f" "^set -euo pipefail$" "from the template"
set +e; "$M" --new "Bad Slug" >/dev/null 2>&1; rc=$?; set -e
assert_eq "$rc" "1" "a slug with spaces or capitals is refused"
rm -f "$f"
set +e; /bin/bash "$M" --pending >/dev/null; rc=$?; set -e
assert_eq "$rc" "1" "runs under /bin/bash 3.2"
echo ""

section "Test 4: The repo's own migrations"
for real in "$ROOT"/migrations/*.sh; do
    /bin/bash -n "$real" || fail "every migration parses under /bin/bash 3.2" "$(basename "$real")"
done
pass "every migration parses under /bin/bash 3.2"

state="$TEST_TMP/real-state"
mkdir -p "$state" && chmod 755 "$state"
DOTFILES_STATE_DIR="$state" bash "$ROOT"/migrations/*-private-state-dir.sh >/dev/null
assert_eq "$(stat -f '%Lp' "$state")" "700" "private-state-dir makes the state dir 700"
DOTFILES_STATE_DIR="$state" bash "$ROOT"/migrations/*-private-state-dir.sh >/dev/null
assert_eq "$(stat -f '%Lp' "$state")" "700" "and a second run keeps it"

mkdir -p "$HOME/.config/lsd"
# shellcheck disable=SC2016  # the backticks are literal header text
printf '# Generated by `dotfiles theme` from themes/aura/colors.toml — do not edit.\nuser: ffffff\n' > "$HOME/.config/lsd/colors.yaml"
bash "$ROOT"/migrations/*-drop-lsd-colors.sh >/dev/null
assert_file_not_exists "$HOME/.config/lsd/colors.yaml" "drop-lsd-colors removes the generated file"
assert_dir_not_exists "$HOME/.config/lsd" "and the emptied directory"
mkdir -p "$HOME/.config/lsd"
echo "user: mine" > "$HOME/.config/lsd/colors.yaml"
bash "$ROOT"/migrations/*-drop-lsd-colors.sh >/dev/null
assert_file_contains "$HOME/.config/lsd/colors.yaml" "user: mine" "but keeps one the user wrote"
echo ""
