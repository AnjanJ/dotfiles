#!/usr/bin/env bash
# Migration: remove the lsd colours `dotfiles theme` used to write
#
# eza is the `ls` here (the aliases in .zshrc-terminal-enhancements), so
# the theme now colours eza (~/.config/eza/theme.yml) and lsd left the
# Brewfile. The rendered ~/.config/lsd/colors.yaml is no longer updated;
# remove it if it is ours (it starts with the generated header), and the
# directory if that leaves it empty. lsd itself is not uninstalled:
# `dotfiles cleanup` lists it as not in the Brewfile.
set -euo pipefail

f="$HOME/.config/lsd/colors.yaml"
# shellcheck disable=SC2016  # the backticks are literal text in the header
if [[ -f "$f" ]] && head -1 "$f" | grep -q '^# Generated by `dotfiles theme`'; then
    rm -f "$f"
    rmdir "$HOME/.config/lsd" 2>/dev/null || true
    echo "    removed the generated ~/.config/lsd/colors.yaml"
fi
