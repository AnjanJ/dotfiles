#!/bin/bash

# Updates-waiting plugin for SketchyBar.
#
# Shows "↑ N" when N kinds of thing are waiting (repo commits, Homebrew
# upgrades, dropped or kept packages, migrations, restarts) and hides
# otherwise. It reads only the result `dotfiles update available` saved last
# (refreshed once a day by the login shell and by `dotfiles update`), via
# --cached, so the bar never fetches or calls brew. A click (argument
# "notify") posts the full list as a notification.

# Sketchybar spawns plugins from the bar daemon's own environment, so the
# `export`s in sketchybarrc do NOT reach them. colors.sh carries the same
# palette as a standalone file and is regenerated by apply-theme.sh.
# shellcheck source=/dev/null
[ -f "$HOME/.config/sketchybar/colors.sh" ] && . "$HOME/.config/sketchybar/colors.sh"
YELLOW="${YELLOW:-0xffffca85}"

# ~/bin is where `dotfiles doctor` links the commands; before that has run
# the plugin still works from the checkout it was symlinked out of.
CHECK="$HOME/bin/dotfiles-update-available"
[ -x "$CHECK" ] || CHECK="$(dirname "$(readlink -f "$0")")/../../../bin/dotfiles-update-available"

# Exit 1 means nothing is waiting; any output then is not a list.
LINES="$("$CHECK" --cached 2>/dev/null)" || LINES=""

if [ "${1:-}" = "notify" ]; then
    [ -n "$LINES" ] || LINES="Everything is up to date"
    MSG="$(printf '%s\n' "$LINES" | tr '\n' ';' | sed 's/;$//; s/;/ · /g')"
    DOTFILES_UPDATES_MSG="$MSG" osascript -e 'display notification (system attribute "DOTFILES_UPDATES_MSG") with title "dotfiles updates"' >/dev/null 2>&1 || true
    exit 0
fi

if [ -z "$LINES" ]; then
    sketchybar --set "$NAME" drawing=off
    exit 0
fi

COUNT=$(printf '%s\n' "$LINES" | grep -c .)
sketchybar --set "$NAME" drawing=on label="↑ $COUNT" label.color="$YELLOW"
