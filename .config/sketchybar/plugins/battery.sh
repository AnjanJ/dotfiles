#!/bin/bash

# Battery plugin for SketchyBar.
#
# Shown only when the battery is doing something: running on battery or
# charging. On AC with nothing to do (charged, or held below full by
# optimised charging) a permanent "100%" is noise, so the item hides. A Mac
# without a battery never shows it.
#
# Colour by charge: green from 80%, orange 51-79%, yellow 40-50%, red below
# 40%. Besides its 120s poll the item subscribes to power_source_change and
# system_woke in sketchybarrc, so plugging in or opening the lid repaints it
# at once.

# Sketchybar spawns plugins from the bar daemon's own environment, so the
# `export`s in sketchybarrc do NOT reach them. colors.sh carries the same
# palette as a standalone file and is regenerated by apply-theme.sh, so
# switching themes recolours these items too.
# shellcheck source=/dev/null
[ -f "$HOME/.config/sketchybar/colors.sh" ] && . "$HOME/.config/sketchybar/colors.sh"

# Fallbacks keep the item readable if colors.sh is missing (fresh clone
# before a theme has ever been applied) rather than rendering colourless.
RED="${RED:-0xffff6767}"
YELLOW="${YELLOW:-0xffffca85}"
ORANGE="${ORANGE:-0xffffa066}"
GREEN="${GREEN:-0xff61ffca}"

# One call: "Now drawing from 'AC Power'" then
# " -InternalBattery-0 (id=...)	87%; charging; 0:40 remaining present: true".
BATT=$(pmset -g batt)
PERCENTAGE=$(printf '%s\n' "$BATT" | grep -Eo '[0-9]+%' | head -1 | tr -d '%')
STATE=$(printf '%s\n' "$BATT" | awk -F'; ' '/%;/ {print $2; exit}')

if [ -z "$PERCENTAGE" ]; then
    sketchybar --set "$NAME" drawing=off
    exit 0
fi

# "charging" and "finishing charge" both mean power is going in. On AC any
# other state (charged, "AC attached; not charging") has nothing to report.
case "$STATE" in
    charging|"finishing charge") CHARGING=1 ;;
    *) CHARGING=0 ;;
esac
if [ "$CHARGING" -eq 0 ] && printf '%s\n' "$BATT" | grep -q "'AC Power'"; then
    sketchybar --set "$NAME" drawing=off
    exit 0
fi

if [ "$PERCENTAGE" -ge 80 ]; then
    COLOR=$GREEN
elif [ "$PERCENTAGE" -gt 50 ]; then
    COLOR=$ORANGE
elif [ "$PERCENTAGE" -ge 40 ]; then
    COLOR=$YELLOW
else
    COLOR=$RED
fi

if [ "$CHARGING" -eq 1 ]; then
    ICON=""
elif [ "$PERCENTAGE" -gt 80 ]; then
    ICON=""
elif [ "$PERCENTAGE" -gt 60 ]; then
    ICON=""
elif [ "$PERCENTAGE" -gt 40 ]; then
    ICON=""
elif [ "$PERCENTAGE" -gt 20 ]; then
    ICON=""
else
    ICON=""
fi

sketchybar --set "$NAME" drawing=on icon="$ICON" label="${PERCENTAGE}%" label.color="$COLOR" icon.color="$COLOR"
